import pytest

from tmd_plain.classify.keyword import keyword_label

# ตัวอย่างจากนิยามป้ายในคู่มือหัวข้อ 2 และ 4 (ไม่ใช่จากชุดทดสอบ)


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("ขอให้ประชาชนติดตามประกาศจากกรมอุตุนิยมวิทยาอย่างต่อเนื่อง", "advice"),
        ("ชาวเรือควรตรวจสอบเส้นทางและเดินเรือด้วยความระมัดระวัง", "advice"),
        ("เรือเล็กบริเวณอ่าวไทยตอนล่างควรงดออกจากฝั่ง", "advice"),
        ("ขอให้ประชาชนดูแลรักษาสุขภาพ เนื่องจากสภาพอากาศที่หนาวเย็นลง", "advice"),
        ("ทั้งนี้เนื่องจากบริเวณความกดอากาศสูงหรือมวลอากาศเย็นที่ปกคลุมภาคเหนือตอนบนมีกำลังอ่อนลง", "cause"),
        ("ส่วนมรสุมตะวันออกเฉียงเหนือกำลังปานกลางพัดปกคลุมบริเวณอ่าวไทยและภาคใต้", "cause"),
        ("ประกอบกับคลื่นกระแสลมฝ่ายตะวันตกเคลื่อนผ่านประเทศเมียนมา", "cause"),
        ("พยากรณ์อากาศ 24 ชั่วโมงข้างหน้า ภาคใต้ยังคงมีฝนตกต่อเนื่อง และมีฝนตกหนักหลายพื้นที่", "weather"),
        ("อ่าวไทยตอนล่างมีคลื่นสูงประมาณ 2 เมตร บริเวณที่มีฝนฟ้าคะนองคลื่นสูงมากกว่า 3 เมตร", "weather"),
        ("ออกประกาศ 16 พฤศจิกายน 2569", "other"),
        ("12:00", "other"),
    ],
)
def test_keyword_label(text: str, expected: str) -> None:
    assert keyword_label(text) == expected
